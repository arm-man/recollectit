INSERT INTO questions (
    subject_id,
    category_id,
    question_text,
    answer_text
)
SELECT
    s.id,
    c.id,
    d.country,
    d.capital
FROM capital_data AS d
CROSS JOIN world_capitals_subject AS s
JOIN categories AS c
    ON c.subject_id = s.id
   AND c.title = d.continent
WHERE NOT EXISTS (
    SELECT 1
    FROM questions AS q
    WHERE q.subject_id = s.id
      AND q.category_id = c.id
      AND q.question_text = d.country
      AND q.answer_text = d.capital
);
